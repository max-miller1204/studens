/** Vendor pinned UI assets. Validate every package in scratch space before writes.
 * Run: node scripts/vendor-ui.ts <inter> <source-serif-4> <jetbrains-mono> <lucide> [--output <vendor-directory>]
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const names = [
  "sun",
  "moon",
  "book-open",
  "library",
  "folder",
  "folder-open",
  "search",
  "arrow-left",
  "arrow-right",
  "chevron-left",
  "chevron-right",
  "chevron-down",
  "plus",
  "x",
  "check",
  "circle-alert",
  "info",
  "settings",
  "bookmark",
  "highlighter",
  "message-circle",
  "clock",
  "rotate-ccw",
  "download",
  "external-link",
];
const args = process.argv.slice(2);
if (
  ![4, 6].includes(args.length) ||
  !args.slice(0, 4).every((v) => /^\d+\.\d+\.\d+$/.test(v)) ||
  (args.length === 6 && (args[4] !== "--output" || !args[5]))
)
  throw new Error(
    "Usage: node scripts/vendor-ui.ts <inter> <source-serif-4> <jetbrains-mono> <lucide> [--output <vendor-directory>]",
  );
const root = fileURLToPath(new URL("../", import.meta.url));
const output = args.length === 6 ? path.resolve(args[5]) : path.join(root, "assets/runtime/vendor");
const work = fs.mkdtempSync(path.join(os.tmpdir(), "studens-vendor-ui-"));
const staged = path.join(work, "validated");
fs.mkdirSync(staged);
const hash = (file: string) => createHash("sha256").update(fs.readFileSync(file)).digest("hex");
const sourceSerifLicense =
  "https://raw.githubusercontent.com/google/fonts/01aa15d05749e35be9167f3f44e6a243f00cd2fc/ofl/sourceserif4/OFL.txt";

try {
  for (const [index, id] of ["inter", "source-serif-4", "jetbrains-mono", "lucide"].entries()) {
    const version = args[index];
    const pkg = id === "lucide" ? "lucide-static" : `@fontsource-variable/${id}`;
    const download = path.join(work, id);
    fs.mkdirSync(download);
    const [packed] = JSON.parse(
      execFileSync("npm", ["pack", `${pkg}@${version}`, "--json", "--ignore-scripts"], {
        cwd: download,
        encoding: "utf8",
      }),
    );
    if (packed.name !== pkg || packed.version !== version || !packed.integrity)
      throw new Error(`Unexpected npm package for ${pkg}@${version}.`);
    execFileSync("tar", ["xzf", packed.filename], { cwd: download });
    const unpacked = path.join(download, "package");
    const manifest = JSON.parse(fs.readFileSync(path.join(unpacked, "package.json"), "utf8"));
    if (manifest.name !== pkg || manifest.version !== version)
      throw new Error(`Package manifest does not match ${pkg}@${version}.`);
    const license = fs.readFileSync(path.join(unpacked, "LICENSE"), "utf8");
    if (
      id === "lucide"
        ? !license.includes("ISC License") || !license.includes("Cole Bemis")
        : !license.includes("SIL OPEN FONT LICENSE")
    )
      throw new Error(`Missing required license notices for ${pkg}.`);
    const target = path.join(staged, id);
    fs.mkdirSync(target);
    fs.writeFileSync(path.join(target, "LICENSE"), license);
    fs.writeFileSync(path.join(target, "VERSION"), `${version}\n`);
    if (id === "source-serif-4") {
      const response = await fetch(sourceSerifLicense, { signal: AbortSignal.timeout(30_000) });
      if (!response.ok)
        throw new Error(`Source Serif 4 upstream license: HTTP ${response.status}.`);
      const upstream = await response.text();
      if (
        !upstream.includes("The Source Serif 4 Project Authors") ||
        !upstream.includes("SIL OPEN FONT LICENSE")
      )
        throw new Error("Source Serif 4 upstream license is missing required notices.");
      fs.writeFileSync(path.join(target, "OFL.upstream.txt"), upstream);
    }
    if (id === "lucide") {
      const icons: Record<string, string> = {};
      for (const name of names) {
        const source = fs.readFileSync(path.join(unpacked, "icons", `${name}.svg`), "utf8");
        const body = source.match(/<svg\b[\s\S]*?>([\s\S]*?)<\/svg>/)?.[1].trim();
        if (
          !body ||
          /<(?!\/?(?:path|circle|rect|line|polyline|polygon|ellipse)\b)/.test(body) ||
          /\bon\w+\s*=|href\s*=|url\s*\(/i.test(body)
        )
          throw new Error(`Unexpected SVG content in ${name}.`);
        const svg = `<svg xmlns="http://www.w3.org/2000/svg" class="cl-icon" width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${body}</svg>`;
        fs.writeFileSync(path.join(target, `${name}.svg`), `${svg}\n`);
        icons[name] = svg;
      }
      fs.writeFileSync(
        path.join(target, "icons.mjs"),
        `// Generated by scripts/vendor-ui.ts. See LICENSE for ISC and Feather MIT notices.\nexport const icons = Object.freeze(${JSON.stringify(icons, null, 2)});\n`,
      );
    } else {
      const rules: string[] = [];
      for (const style of ["normal", "italic"]) {
        const css = fs.readFileSync(
          path.join(unpacked, style === "normal" ? "wght.css" : "wght-italic.css"),
          "utf8",
        );
        for (const subset of ["latin", "latin-ext"]) {
          const filename = `${id}-${subset}-wght-${style}.woff2`;
          const block = [...css.matchAll(/@font-face\s*\{[^}]+\}/g)]
            .map((m) => m[0])
            .find((block) => block.includes(`./files/${filename}`));
          if (
            !block ||
            !block.includes("font-display: swap") ||
            !block.includes("unicode-range:") ||
            !/font-weight: \d+ \d+;/.test(block)
          )
            throw new Error(`Missing variable font declaration for ${filename}.`);
          const source = path.join(unpacked, "files", filename);
          if (fs.readFileSync(source).subarray(0, 4).toString() !== "wOF2")
            throw new Error(`Invalid WOFF2 file: ${filename}.`);
          fs.copyFileSync(source, path.join(target, filename));
          rules.push(block.replace(`./files/${filename}`, `./${filename}`));
        }
      }
      fs.writeFileSync(
        path.join(target, "font.css"),
        `/* ${pkg}@${version}. See LICENSE (OFL-1.1) and PROVENANCE.json. */\n${rules.join("\n\n")}\n`,
      );
      fs.copyFileSync(path.join(unpacked, "metadata.json"), path.join(target, "metadata.json"));
    }
    const files = Object.fromEntries(
      fs
        .readdirSync(target)
        .sort()
        .map((file) => [file, hash(path.join(target, file))]),
    );
    fs.writeFileSync(
      path.join(target, "PROVENANCE.json"),
      `${JSON.stringify({ package: pkg, version, source: `https://registry.npmjs.org/${pkg}/-/${pkg.split("/").at(-1)}-${version}.tgz`, integrity: packed.integrity, repository: manifest.repository, ...(id === "source-serif-4" ? { upstreamLicense: sourceSerifLicense } : {}), transformation: id === "lucide" ? "Named subset. Decorative SVGs use currentColor, 18px size, and 1.75 stroke. icons.mjs contains the same SVG bytes." : "Unmodified variable weight Latin and Latin-Extended normal/italic WOFF2. Subset CSS retains upstream unicode ranges.", files }, null, 2)}\n`,
    );
  }
  // All required files and licenses have passed validation.
  fs.mkdirSync(output, { recursive: true });
  for (const id of ["inter", "source-serif-4", "jetbrains-mono", "lucide"]) {
    const target = path.join(output, id);
    fs.rmSync(target, { recursive: true, force: true });
    fs.cpSync(path.join(staged, id), target, { recursive: true });
  }
  console.log(`Vendored UI assets into ${output}`);
} finally {
  fs.rmSync(work, { recursive: true, force: true });
}
